const MONTH_NAMES = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export const formatDateDisplay = (date: Date): string => {
  const d = String(date.getDate()).padStart(2, "0");
  const m = MONTH_NAMES[date.getMonth()];
  const y = date.getFullYear();
  return `${d}-${m}-${y}`;
};

export const formatDateTimeDisplay = (date: Date): string => {
  const d = formatDateDisplay(date);
  const hours = String(date.getHours()).padStart(2, "0");
  const minutes = String(date.getMinutes()).padStart(2, "0");
  return `${d} ${hours}:${minutes} IST`;
};

export const formatCurrencyINR = (amount: number): string => {
  return Number(amount || 0).toLocaleString("en-IN", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
};

export interface CompanyInfo {
  name: string;
  legalName?: string | null;
  gstin?: string | null;
  cityState?: string;
  currency: string;
}

export const getCompanyInfo = async (companyId: number): Promise<CompanyInfo> => {
  const c = await prisma.company.findUnique({
    where: { id: companyId },
    select: { name: true, legalName: true, gstin: true, city: true, state: true, currency: true },
  });
  const name = c?.legalName || c?.name || "MEHTA JEWELLERS";
  const cityState = [c?.city, c?.state].filter(Boolean).join(", ");
  return {
    name,
    legalName: c?.legalName,
    gstin: c?.gstin,
    cityState,
    currency: c?.currency || "INR",
  };
};

export interface ReportMeta {
  title: string;
  periodLabel: string;
  filenamePeriod: string;
  generatedAt: Date;
}

export interface ExportDataPayload {
  company: CompanyInfo;
  meta: ReportMeta;
  headers: string[];
  alignments?: Array<"left" | "right" | "center">;
  columnWidths?: number[];
  rows: Array<Array<string | number>>;
  summaryRows?: Array<Array<string | number>>;
  note?: string;
}

