// 1. CSV GENERATOR
// -------------------------------------------------------------
export const generateCsv = (payload: ExportDataPayload): Buffer => {
  const lines: string[] = [];

  // UTF-8 BOM for Excel compatibility
  const BOM = "\uFEFF";

  // Formal Header Block
  lines.push(`"${payload.company.name.replace(/"/g, '""')}"`);
  if (payload.company.gstin) {
    lines.push(`"GSTIN: ${payload.company.gstin}"`);
  }
  if (payload.company.cityState) {
    lines.push(`"${payload.company.cityState}"`);
  }
  lines.push(`"${payload.meta.title.toUpperCase()}"`);
  lines.push(`"Reporting Period: ${payload.meta.periodLabel}"`);
  lines.push(`"Generated On: ${formatDateTimeDisplay(payload.meta.generatedAt)}"`);
  lines.push(`"Currency: ${payload.company.currency}"`);
  lines.push(""); // blank line

  // Column Headers
  const headerLine = payload.headers
    .map((h) => `"${String(h).replace(/"/g, '""')}"`)
    .join(",");
  lines.push(headerLine);

  // Data Rows
  for (const row of payload.rows) {
    const rowLine = row
      .map((val) => {
        if (typeof val === "number") {
          return `"${val.toFixed(2)}"`;
        }
        return `"${String(val ?? "").replace(/"/g, '""')}"`;
      })
      .join(",");
    lines.push(rowLine);
  }

  // Summary Rows
  if (payload.summaryRows && payload.summaryRows.length > 0) {
    lines.push(""); // blank line before totals
    for (const sRow of payload.summaryRows) {
      const sLine = sRow
        .map((val) => {
          if (typeof val === "number") {
            return `"${val.toFixed(2)}"`;
          }
          return `"${String(val ?? "").replace(/"/g, '""')}"`;
        })
        .join(",");
      lines.push(sLine);
    }
  }

  if (payload.note) {
    lines.push("");
    lines.push(`"Status: ${payload.note.replace(/"/g, '""')}"`);
  }

  lines.push("");
  lines.push('"Official accounting document generated by JewelLedger Accounting System."');

  return Buffer.from(BOM + lines.join("\r\n"), "utf-8");
};

