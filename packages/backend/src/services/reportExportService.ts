// 3. PDF GENERATOR (.pdf via PDFKit)
// -------------------------------------------------------------
export const generatePdf = (payload: ExportDataPayload): Promise<Buffer> => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        margin: 40,
        size: "A4",
        info: {
          Title: `${payload.meta.title} - ${payload.company.name}`,
          Author: "JewelLedger Accounting",
          Subject: payload.meta.periodLabel,
        },
      });

      const chunks: Buffer[] = [];
      doc.on("data", (chunk: Buffer) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", (err: Error) => reject(err));

      const pageWidth = 595.28;
      const margin = 40;
      const contentWidth = pageWidth - margin * 2;

      // Header Block
      doc.font("Helvetica-Bold").fontSize(15).fillColor("#1E293B").text(payload.company.name, { align: "center" });

      if (payload.company.gstin || payload.company.cityState) {
        const sub = [payload.company.gstin ? `GSTIN: ${payload.company.gstin}` : "", payload.company.cityState].filter(Boolean).join(" | ");
        doc.font("Helvetica").fontSize(9).fillColor("#64748B").text(sub, { align: "center" });
      }

      doc.moveDown(0.4);
      doc.font("Helvetica-Bold").fontSize(12).fillColor("#B45309").text(payload.meta.title.toUpperCase(), { align: "center" });
      doc.font("Helvetica").fontSize(9).fillColor("#475569").text(`Period: ${payload.meta.periodLabel}  |  Generated: ${formatDateTimeDisplay(payload.meta.generatedAt)}`, { align: "center" });

      doc.moveDown(0.6);
      doc.strokeColor("#CBD5E1").lineWidth(1).moveTo(margin, doc.y).lineTo(margin + contentWidth, doc.y).stroke();
      doc.moveDown(0.5);

      // Table Setup
      const numCols = payload.headers.length;
      let colWidths: number[];

      if (numCols === 5) {
        // e.g. Trial Balance: Code, Account Name, Type, Debit, Credit
        colWidths = [50, 225, 80, 80, 80];
      } else if (numCols === 3) {
        // e.g. Code, Name, Amount
        colWidths = [80, 295, 140];
      } else if (numCols === 4) {
        colWidths = [70, 225, 110, 110];
      } else {
        const w = Math.floor(contentWidth / numCols);
        colWidths = Array(numCols).fill(w);
      }

      const drawTableHeader = (startY: number) => {
        doc.rect(margin, startY, contentWidth, 20).fill("#1E293B");
        doc.font("Helvetica-Bold").fontSize(9).fillColor("#FFFFFF");

        let currX = margin;
        payload.headers.forEach((h, i) => {
          const w = colWidths[i];
          const align = payload.alignments?.[i] || "left";
          doc.text(h, currX + (align === "right" ? 0 : 4), startY + 5, {
            width: w - 8,
            align,
          });
          currX += w;
        });
        return startY + 22;
      };

      let currentY = drawTableHeader(doc.y);

      // Render Rows
      payload.rows.forEach((row, rowIndex) => {
        // Page break check
        if (currentY > 760) {
          doc.addPage();
          currentY = drawTableHeader(margin);
        }

        // Alternating row background
        if (rowIndex % 2 === 1) {
          doc.rect(margin, currentY, contentWidth, 16).fill("#F8FAFC");
        }

        doc.font("Helvetica").fontSize(8.5).fillColor("#0F172A");
        let currX = margin;
        row.forEach((cellVal, colIdx) => {
          const w = colWidths[colIdx];
          const align = payload.alignments?.[colIdx] || "left";
          const displayVal = typeof cellVal === "number" ? formatCurrencyINR(cellVal) : String(cellVal ?? "");

          doc.text(displayVal, currX + (align === "right" ? 0 : 4), currentY + 3.5, {
            width: w - 8,
            align,
          });
          currX += w;
        });

        currentY += 17;
      });

      // Render Summary Rows
      if (payload.summaryRows && payload.summaryRows.length > 0) {
        if (currentY > 740) {
          doc.addPage();
          currentY = margin;
        }

        // Top line
        doc.strokeColor("#0F172A").lineWidth(1).moveTo(margin, currentY).lineTo(margin + contentWidth, currentY).stroke();
        currentY += 4;

        payload.summaryRows.forEach((sRow) => {
          doc.rect(margin, currentY, contentWidth, 18).fill("#F1F5F9");
          doc.font("Helvetica-Bold").fontSize(9).fillColor("#0F172A");

          let currX = margin;
          sRow.forEach((cellVal, colIdx) => {
            const w = colWidths[colIdx];
            const align = payload.alignments?.[colIdx] || "left";
            const displayVal = typeof cellVal === "number" ? formatCurrencyINR(cellVal) : String(cellVal ?? "");

            doc.text(displayVal, currX + (align === "right" ? 0 : 4), currentY + 4, {
              width: w - 8,
              align,
            });
            currX += w;
          });

          currentY += 20;
        });

        // Double underline
        doc.strokeColor("#0F172A").lineWidth(1).moveTo(margin, currentY).lineTo(margin + contentWidth, currentY).stroke();
        doc.strokeColor("#0F172A").lineWidth(1).moveTo(margin, currentY + 2).lineTo(margin + contentWidth, currentY + 2).stroke();
        currentY += 8;
      }

      if (payload.note) {
        if (currentY > 770) {
          doc.addPage();
          currentY = margin;
        }
        doc.font("Helvetica-Bold").fontSize(9).fillColor("#047857").text(`Status: ${payload.note}`, margin, currentY + 4);
        currentY += 16;
      }

      // Footer
      const totalPages = doc.bufferedPageRange().count;
      for (let i = 0; i < totalPages; i++) {
        doc.switchToPage(i);
        doc.font("Helvetica").fontSize(7.5).fillColor("#94A3B8").text(
          `JewelLedger Financial Accounting  •  Page ${i + 1} of ${totalPages}  •  Formal Computer Generated Report`,
          margin,
          810,
          { align: "center", width: contentWidth }
        );
      }

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
};
