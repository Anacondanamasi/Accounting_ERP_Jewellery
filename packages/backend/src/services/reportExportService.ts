// 2. EXCEL GENERATOR (.xlsx via ExcelJS)
// -------------------------------------------------------------
export const generateExcel = async (payload: ExportDataPayload): Promise<Buffer> => {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "JewelLedger Accounting";
  workbook.lastModifiedBy = "JewelLedger Accounting";
  workbook.created = payload.meta.generatedAt;
  workbook.modified = payload.meta.generatedAt;

  const worksheet = workbook.addWorksheet(payload.meta.title.slice(0, 31), {
    views: [{ showGridLines: true }],
  });

  // Title & Metadata Styling
  const titleRow = worksheet.addRow([payload.company.name]);
  titleRow.font = { name: "Calibri", size: 16, bold: true, color: { argb: "FF1E293B" } };

  if (payload.company.gstin) {
    const gstinRow = worksheet.addRow([`GSTIN: ${payload.company.gstin} | ${payload.company.cityState || ""}`]);
    gstinRow.font = { name: "Calibri", size: 10, color: { argb: "FF64748B" } };
  }

  const reportRow = worksheet.addRow([payload.meta.title.toUpperCase()]);
  reportRow.font = { name: "Calibri", size: 13, bold: true, color: { argb: "FFB45309" } };

  const periodRow = worksheet.addRow([`Period: ${payload.meta.periodLabel} | Generated: ${formatDateTimeDisplay(payload.meta.generatedAt)} | Currency: ${payload.company.currency}`]);
  periodRow.font = { name: "Calibri", size: 10, italic: true, color: { argb: "FF475569" } };

  worksheet.addRow([]); // Blank spacing row

  // Table Column Headers
  const headerRow = worksheet.addRow(payload.headers);
  headerRow.height = 24;
  headerRow.eachCell((cell, colIndex) => {
    cell.font = { name: "Calibri", size: 11, bold: true, color: { argb: "FFFFFFFF" } };
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF1E293B" }, // dark slate navy
    };
    cell.alignment = {
      vertical: "middle",
      horizontal: payload.alignments?.[colIndex - 1] === "right" ? "right" : "left",
    };
    cell.border = {
      top: { style: "thin", color: { argb: "FF94A3B8" } },
      bottom: { style: "medium", color: { argb: "FF0F172A" } },
      left: { style: "thin", color: { argb: "FF334155" } },
      right: { style: "thin", color: { argb: "FF334155" } },
    };
  });

  // Data Rows
  for (const rowData of payload.rows) {
    const row = worksheet.addRow(rowData);
    row.height = 20;
    row.eachCell((cell, colIndex) => {
      cell.font = { name: "Calibri", size: 10 };
      const align = payload.alignments?.[colIndex - 1] || "left";
      cell.alignment = { vertical: "middle", horizontal: align };

      if (typeof cell.value === "number") {
        cell.numFmt = "#,##0.00";
      }

      cell.border = {
        bottom: { style: "thin", color: { argb: "FFE2E8F0" } },
        left: { style: "thin", color: { argb: "FFF1F5F9" } },
        right: { style: "thin", color: { argb: "FFF1F5F9" } },
      };
    });
  }

  // Summary Rows
  if (payload.summaryRows && payload.summaryRows.length > 0) {
    for (const sData of payload.summaryRows) {
      const sRow = worksheet.addRow(sData);
      sRow.height = 22;
      sRow.eachCell((cell, colIndex) => {
        cell.font = { name: "Calibri", size: 11, bold: true, color: { argb: "FF0F172A" } };
        cell.fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: { argb: "FFF8FAFC" },
        };
        const align = payload.alignments?.[colIndex - 1] || "left";
        cell.alignment = { vertical: "middle", horizontal: align };

        if (typeof cell.value === "number") {
          cell.numFmt = "#,##0.00";
        }

        cell.border = {
          top: { style: "thin", color: { argb: "FF0F172A" } },
          bottom: { style: "double", color: { argb: "FF0F172A" } },
        };
      });
    }
  }

  if (payload.note) {
    worksheet.addRow([]);
    const noteRow = worksheet.addRow([`Status: ${payload.note}`]);
    noteRow.font = { name: "Calibri", size: 10, bold: true, color: { argb: "FF047857" } };
  }

  // Adjust column widths automatically
  worksheet.columns.forEach((col, index) => {
    if (payload.columnWidths && payload.columnWidths[index]) {
      col.width = payload.columnWidths[index];
    } else {
      let maxLen = 12;
      col.eachCell?.({ includeEmpty: false }, (cell) => {
        const valStr = cell.value ? String(cell.value) : "";
        if (valStr.length > maxLen) maxLen = Math.min(valStr.length + 3, 50);
      });
      col.width = Math.max(maxLen, 14);
    }
  });

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
};

